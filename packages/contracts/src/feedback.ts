export const FEEDBACK_KINDS = ['bug', 'idea', 'other'] as const;
export type FeedbackPreferences = { promptsEnabled: boolean; revision: number };
export type SaveFeedbackPreferences = { promptsEnabled: boolean; expected_revision: number; client_request_id: string };
export const FEEDBACK_STATUSES = ['new', 'reviewing', 'resolved'] as const;
export const FEEDBACK_PAGES = ['Explore', 'My projects', 'My agents', 'Project', 'My profile', 'Needs you', 'Other'] as const;
export type FeedbackKind = typeof FEEDBACK_KINDS[number];
export type FeedbackStatus = typeof FEEDBACK_STATUSES[number];
export type FeedbackPage = typeof FEEDBACK_PAGES[number];
export type FeedbackInput = { client_request_id: string; kind: FeedbackKind; body: string; page: FeedbackPage | null; screenshot: { mime: string; base64: string } | null };
export type FeedbackSummary = { id: string; authorName: string; kind: FeedbackKind; status: FeedbackStatus; preview: string; createdAt: number; revision: number; hasScreenshot: boolean };
export type FeedbackReport = FeedbackSummary & { body: string; page: FeedbackPage | null; updatedAt: number };
export type FeedbackInbox = { actorProfileId: string; items: FeedbackSummary[]; next: string | null };
