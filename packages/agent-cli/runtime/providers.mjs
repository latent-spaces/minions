const ENV_NAME = /^[A-Za-z_][A-Za-z0-9_]{0,127}$/;

export function passEnvNames(raw = '') {
  const names = String(raw).split(',').map(v => v.trim()).filter(Boolean);
  if (names.length > 64 || names.some(v => !ENV_NAME.test(v))) throw new Error('PILOT_PASS_ENV lists at most 64 variable names separated by commas, for example GH_TOKEN,HTTPS_PROXY.');
  return names;
}

export function childEnv(id, source, extraNames = [], platform = process.platform) {
  const key = platform === 'win32' ? v => v.toUpperCase() : v => v;
  const allowed = new Set([...COMMON_ENV, ...PROVIDER_ENV[id], ...extraNames].map(key));
  return Object.fromEntries(Object.entries(source).filter(([name, value]) => typeof value === 'string'
    && (allowed.has(key(name)) || /^LC_[A-Z]+$/.test(name))));
}

export function createProvider(id, settings, { envSource = process.env } = {}) {
  if (!PROVIDERS.includes(id)) throw new Error('Select PILOT_PROVIDER=claude or codex. Providers never switch automatically.');
  if(settings.effort!==undefined&&(id!=='codex'||!safeName(settings.effort)))throw new Error('A pinned effort requires a supported Codex effort name.');
  const command = id === 'codex' ? settings.codex : settings.claude;
  const newMcpName = () => `project_${randomUUID().replaceAll('-', '')}`;
  const passEnv = passEnvNames(settings.passEnv);
  const environment = (extra = {}) => ({ ...childEnv(id, envSource, passEnv), ...extra });
  // Listed again for every turn: config can change while the runner is up, and disabling a server that is
  // no longer configured makes App Server refuse to start. Plugin-provided servers have no config entry to
  // disable, so plugins are off in both the listing and the invocation.
  const probe = async (args, options = {}) => {
    try {
      const native = process.platform === 'win32' ? resolveWindowsCommand(command, args, { env: environment(), cwd: options.cwd ?? settings.repoDir }) : { command, args };
      return { ...await executeFile(native.command, native.args, { env: environment(), encoding: 'utf8', timeout: 15_000, maxBuffer: 1024 * 1024, killSignal: 'SIGKILL', windowsHide: true, ...options }), status: 0 };
    }
    catch (error) { options.signal?.throwIfAborted(); return { error, status: error.code, stdout: error.stdout ?? '' }; }
  };
  const mcpServers = async (cwd, signal, requireMergePolicy = false) => {
    const list = await probe(['-c', 'features.plugins=false', '-c', 'features.hooks=false', '-c', 'features.apps=false', ...(requireMergePolicy && generatedRulesOnly(cwd) ? ['-c', codexProjectTrust(cwd)] : []), 'mcp', 'list', '--json'], { cwd, signal });
    if (list.error || list.status !== 0) throw new Error('Cannot inspect local MCP configuration before isolating the project connection.');
    let servers; try { servers = JSON.parse(list.stdout); } catch { throw new Error('Invalid local MCP configuration listing.'); }
    if (!Array.isArray(servers) || servers.length > 128 || servers.some(v => typeof v?.name !== 'string' || !/^[A-Za-z0-9_-]{1,150}$/.test(v.name))) throw new Error('Unsupported local MCP configuration listing.');
    return servers.map(v => v.name);
  };
  return {
    id, environment,
    async preflight({ signal } = {}) {
      signal?.throwIfAborted();
      if (id === 'codex' && settings.turnBudgetUsd > 0) throw new Error('Codex CLI cannot enforce a dollar cap. Remove PILOT_TURN_BUDGET_USD or choose Claude explicitly.');
      if (![undefined, 'acceptEdits'].includes(settings.permissionMode)) throw new Error('Background workers require the local-development permission policy; full-access modes are not supported.');
      const versionProbe = await probe(['--version'], { signal });
      if (versionProbe.error || versionProbe.status !== 0) throw new Error(`Cannot run ${id} --version. Install the local client or set PILOT_${id.toUpperCase()}.`);
      if (id === 'codex') {
        const version = /codex-cli (\d+)\.(\d+)\.(\d+)/.exec(versionProbe.stdout);
        if (!version || +version[1] === 0 && +version[2] < 160) throw new Error('This adapter requires Codex CLI 0.160.0 or newer.');
        const login = await probe(['login', 'status'], { signal });
        if (login.error || login.status !== 0) throw new Error('Sign in locally with codex login, then start the runner again. No credentials were copied.');
        await mcpServers(settings.repoDir, signal);
      }
      return { label: text(versionProbe.stdout.trim(), 150) };
    },
    newSession(promptHash, repoDir) {
      return { id: id === 'claude' ? randomUUID() : null, provider: id, promptHash, repoDir, costUsd: null, ...(id === 'codex' ? { mcpName: newMcpName() } : {}) };
    },
    canResume(session) { return id === 'claude' ? typeof session?.id === 'string' : session?.provider === id && UUID.test(session?.id ?? ''); },
    async validateMergeRules(file, mode, { signal } = {}) {
      if (id !== 'codex') return;
      const result = await probe(['execpolicy', 'check', '--rules', file, '--', 'gh', 'pr', 'merge', '1'], { signal });
      let value; try { value = JSON.parse(result.stdout); } catch {}
      if (result.error || !value || (agentsMayMerge(mode) ? value.decision === 'forbidden' || value.matchedRules?.length !== 0 : value.decision !== 'forbidden')) throw new Error('Installed Codex cannot validate the required native merge policy. Update Codex before starting this worker.');
    },
    async invocation({ prompt, permissionGuidance, instructionsFile, settingsFile, mcpConfig, bridge, session, resuming, repoDir, clientVersion, signal, requireMergePolicy = false, privatePaths }) {
      signal?.throwIfAborted();
      if (![undefined, 'acceptEdits'].includes(settings.permissionMode)) throw new Error('Background workers require the local-development permission policy; full-access modes are not supported.');
      if (id === 'claude') {
        const args = ['-p', prompt, '--output-format', 'stream-json', '--verbose', '--append-system-prompt-file', instructionsFile,
          '--setting-sources=', '--settings', settingsFile, '--disable-slash-commands', '--mcp-config', mcpConfig, '--strict-mcp-config',
          '--permission-mode', settings.permissionMode, '--permission-prompts', 'none', '--allowedTools', settings.allowedTools,
          resuming ? '--resume' : '--session-id', session.id];
        if (settings.turnBudgetUsd > 0) args.push('--max-budget-usd', String(settings.turnBudgetUsd));
        if (settings.model) args.push('--model', settings.model);
        return { command, args };
      }
      const endpoint = new URL(bridge.url);
      const token = bridge.headers?.Authorization?.replace(/^Bearer /, '');
      if (endpoint.protocol !== 'http:' || endpoint.hostname !== '127.0.0.1' || !token) throw new Error('Codex requires the authenticated local project bridge.');
      if (typeof clientVersion !== 'string' || !clientVersion) throw new Error('Codex requires the installed kit version.');
      // The adapter supplies canonical private paths; experiment-only callers derive the same boundary from their
      // instructions directory. No Codex invocation may silently fall back to unrestricted private-state reads.
      privatePaths ??= workerPrivatePaths({ stateDir: dirname(instructionsFile), folder: repoDir, envSource });
      workerCodexProfile({}, privatePaths); // Refuse unrepresentable paths before spawning the native client.
      const permissionProfile = `minions_worker_${randomUUID().replaceAll('-', '')}`;
      const access = { approvalPolicy: 'on-request', approvalsReviewer: 'auto_review' };
      const config = {
        model_provider: '"openai"', approval_policy: `"${access.approvalPolicy}"`,
        approvals_reviewer: '"auto_review"',
        ...(settings.effort?{model_reasoning_effort:tomlString(settings.effort)}:{}),
        ...(requireMergePolicy && generatedRulesOnly(repoDir) ? { projects: `{${JSON.stringify(realpathSync.native(repoDir))}={trust_level="trusted"}}` } : {}),
        developer_instructions: tomlString(readFileSync(instructionsFile, 'utf8') + '\n' + (permissionGuidance ?? localPermissionGuidance(undefined, id))),
        'features.hooks': 'false', 'features.apps': 'false', 'features.plugins': 'false', 'features.multi_agent': 'false', 'features.goals': 'false',
        'memories.generate_memories': 'false', 'memories.use_memories': 'false',
        'shell_environment_policy.filters.PILOT_BRIDGE_TOKEN': '"exclude"',
      };
      // App Server exposes resolved model identity, reroutes and full token-usage notifications.
      // Disable the configured personal MCPs in this invocation only; never edit client config. The project server is
      // set key by key: a whole mcp_servers table override would replace these disables and re-enable personal servers.
      const configured = await mcpServers(repoDir, signal, requireMergePolicy);
      for (const name of configured) config[`mcp_servers.${name}.enabled`] = 'false';
      // The session keeps the project server's name, which the runner saves with it: a thread resumed after a runner
      // restart remembers its tools by that name. A new name is chosen only if a configured server now uses it.
      if (!/^project_[0-9a-f]{32}$/.test(session.mcpName ?? '')) session.mcpName = newMcpName();
      while (configured.includes(session.mcpName)) session.mcpName = newMcpName();
      const mcpName = session.mcpName;
      Object.assign(config, { [`mcp_servers.${mcpName}.url`]: tomlString(bridge.url),
        [`mcp_servers.${mcpName}.bearer_token_env_var`]: '"PILOT_BRIDGE_TOKEN"', [`mcp_servers.${mcpName}.required`]: 'true',
        [`mcp_servers.${mcpName}.default_tools_approval_mode`]: '"approve"' });
      const args = ['app-server', '--stdio', '--strict-config', ...Object.entries(config).flatMap(([key, value]) => ['-c', `${key}=${value}`])];
      const startParams = { cwd: repoDir, modelProvider: 'openai', ...access,
        ...(settings.model ? { model: settings.model } : {}),
        ...(resuming ? { threadId: session.id, excludeTurns: true } : {}) };
      return { command, args, env: { PILOT_BRIDGE_TOKEN: token }, rpc: { prompt, resuming, startParams, permissionProfile,
        prepareThread: effectiveConfig => ({ ...startParams, permissions: permissionProfile, config: { [`permissions.${permissionProfile}`]: workerCodexProfile(effectiveConfig, privatePaths) } }),
        ...(settings.effort?{effort:settings.effort}:{}),
        ...(requireMergePolicy ? { nativeRuleLayer: join(realpathSync.native(repoDir), '.codex') } : {}), clientInfo: codexClientInfo(clientVersion),
        baseline: resuming ? session.tokenTotals ?? null : [0, 0, 0, 0] } };
    },
    collector(options) { return id === 'codex' ? new CodexStream(options) : new ProviderStream(id, options); },
    usage(report, init) {
      const u = report?.usage;
      let tokens = null;
      if (u && !(id === 'claude' && report?.is_error && report.num_turns === 0)) {
        const source = id === 'codex'
          ? [u.input_tokens, u.output_tokens, u.cached_input_tokens, u.cache_write_input_tokens]
          : [u.input_tokens, u.output_tokens, u.cache_read_input_tokens, u.cache_creation_input_tokens];
        if (source.every(v => v === undefined || counter(v) !== null)) {
          const measured = source.map(counter);
          if (measured.some(v => v !== null)) tokens = { input: measured[0], output: measured[1], cacheRead: measured[2], cacheWrite: measured[3], modelCalls: null };
        }
      }
      return { provider: id, inputSemantics: id === 'codex' ? 'includes-cache' : 'uncached',
        model: safeName(init?.model), modelSource: init?.modelSource ?? (init?.model ? 'provider-report' : 'unknown'), tokens };
    },
    loginHint(detail) { return /not logged in|\/login|invalid api key|authentication/i.test(detail)
      ? id === 'codex' ? ' Sign in locally with codex login.' : ' Sign in locally with claude /login.' : ''; },
    missingSession(stderr) { return id === 'claude' && stderr.includes('No conversation found'); },
  };
}

// Retain only session identity, final text, numeric usage and bounded failure metadata.
// Tool arguments/results and reasoning are never retained or rendered by this collector.
class ProviderStream {
  constructor(provider, { log = () => {}, assistantText = () => {}, action = () => {}, status = () => {}, session = () => {}, metadata = () => {}, permission = () => {}, submitted = () => {}, started = () => {}, persistence = () => {} } = {}) {
    this.provider = provider; this.log = log; this.assistantText = assistantText; this.action = action; this.session = session;
    this.metadata = metadata; this.permission = permission; this.toolNames = new Map(); this.toolCommands = new Map(); this.deniedIds = new Set();
    this.init = null; this.nativeContext = null; this.report = null; this.finalText = ''; this.sessionId = null;
    this.submitted = submitted; this.started = started; this.persistence = persistence; this.pendingPersistence = new Set();
    this.delivery = 'not_submitted'; this.failure = null; this.acknowledging = false;
    this.status = status; this.lastStatus = null;
    this.pending = ''; this.dropping = false; this.truncated = false; this.toolCalls = 0; this.toolIds = new Set();
  }
  feed(chunk) {
    for (const part of String(chunk).split(/(?<=\n)/)) {
      if (!this.dropping && Buffer.byteLength(this.pending) + Buffer.byteLength(part) <= 1024 * 1024) this.pending += part;
      else {
        const bytes = Buffer.byteLength(this.pending) + Buffer.byteLength(part);
        const firstOverflow = !this.dropping;
        this.pending = ''; this.dropping = true; this.truncated = true;
        if (firstOverflow) this.overflow?.(bytes);
      }
      if (part.endsWith('\n')) {
        if (!this.dropping) this.line(this.pending);
        this.pending = ''; this.dropping = false;
      }
    }
  }
  end() { if (!this.dropping && this.pending.trim()) this.line(this.pending); this.pending = ''; }
  identify(value) { if (UUID.test(value ?? '')) { this.sessionId = value; this.session(value); } }
  show(value, label = 'Agent') { if (typeof value === 'string' && value.trim()) { this.assistantText(value); this.log(`${label}: ${value.slice(0, 4000)}`, { kind: 'assistant_text', label, truncated: value.length > 4000 }); } }
  observeStatus(value) {
    for (const status of agentStatuses(value)) if (status !== this.lastStatus) {
      this.lastStatus = status;
      try { this.status(status); } catch { /* Observation failures never interrupt native work. */ }
    }
  }
  count(id) { if (!id || this.toolIds.has(id)) return; if (this.toolIds.size >= 4096) { this.truncated = true; return; } this.toolIds.add(id); this.toolCalls++; }
  act(value) { const name = safeName(value); if (name) { this.log(`Agent action: ${name}`); this.action(name); } }
  observeModel(init) { this.init = init; this.metadata({ model: init.model, modelSource: init.modelSource ?? 'provider-report' }); }
  // Synchronous consumers retain synchronous notification. Async durable consumers
  // gate submission and acknowledgement, with rejection observed immediately.
  persist(callback, commit) {
    const value = callback();
    if (!value || typeof value.then !== 'function') { commit(); return; }
    const pending = Promise.resolve(value).then(commit).catch(error => {
      // The fault observer must not create a second unhandled rejection.
      try { this.persistence(error); } catch { /* Original persistence already failed. */ }
    });
    this.pendingPersistence.add(pending);
    pending.finally(() => this.pendingPersistence.delete(pending));
    return pending;
  }
  async drainPersistence() { while (this.pendingPersistence.size) await Promise.all([...this.pendingPersistence]); }
  submitPrompt() {
    if (this.delivery !== 'not_submitted') return;
    return this.persist(this.submitted, () => { this.delivery = 'submitted'; });
  }
  acknowledgePrompt() {
    if (this.delivery === 'acknowledged' || this.acknowledging) return;
    this.acknowledging = true;
    return this.persist(this.started, () => { this.delivery = 'acknowledged'; });
  }
  observeDenial(id, tool) {
    const name = safeName(tool);
    if (!name || this.deniedIds.size >= 4096 || (id && this.deniedIds.has(id))) return;
    if (id) this.deniedIds.add(id);
    // The refused command stays in the local run record, so a blocked check can be diagnosed afterwards.
    const command = id ? this.toolCommands.get(id) : undefined;
    this.permission({ tool: name, ...(command ? { command } : {}) });
  }
  claudeContext() {
    return this.nativeContext ??= { source: 'claude-stream-json', coverage: 'partial-turn-stream', lastInputTokens: null, lastTotalTokens: null, modelContextWindow: null, observations: 0, completedCompactions: 0 };
  }
  // A request's input is its uncached, cache-read and cache-write tokens together; repeated events of one message count once.
  observeClaudeRequest(message) {
    const u = message?.usage; if (!u || typeof u !== 'object') return;
    const parts = [u.input_tokens, u.cache_read_input_tokens, u.cache_creation_input_tokens].map(v => v === undefined ? 0 : counter(v)), output = u.output_tokens === undefined ? 0 : counter(u.output_tokens);
    if (parts.some(v => v === null) || output === null) return;
    const context = this.claudeContext(), input = parts.reduce((a, b) => a + b, 0), id = typeof message.id === 'string' ? message.id : null;
    context.lastInputTokens = input; context.lastTotalTokens = input + output;
    if (!id || id !== this.lastClaudeMessage) { this.lastClaudeMessage = id; context.observations = Math.min(1e9, context.observations + 1); }
  }
  // The result's per-model usage names each model's window; the agent's own model is the one it started with.
  observeClaudeWindow(modelUsage) {
    if (!modelUsage || typeof modelUsage !== 'object' || !this.nativeContext) return;
    const entries = Object.entries(modelUsage), own = entries.find(([name]) => name === this.init?.model) ?? entries.find(([name]) => this.init?.model && name.startsWith(this.init.model)) ?? (entries.length === 1 ? entries[0] : null);
    const window = counter(own?.[1]?.contextWindow);
    if (window !== null && window > 0) this.nativeContext.modelContextWindow = window;
  }
  line(line) {
    let events;
    try { const parsed = JSON.parse(line); events = Array.isArray(parsed) ? parsed : [parsed]; } catch { return; }
    for (const e of events) {
      if (!e || typeof e !== 'object') continue;
      if (this.provider === 'claude') {
        if (e.type === 'system' && e.subtype === 'init') this.observeModel({ model: safeName(e.model), effort: safeName(e.effort) });
        // The agent's own context: its latest request's input, its model's window and its compactions. Subagent messages are skipped.
        if (e.type === 'assistant' && !e.parent_tool_use_id) this.observeClaudeRequest(e.message);
        if (e.type === 'system' && e.subtype === 'compact_boundary') { this.claudeContext().completedCompactions = Math.min(4096, this.nativeContext.completedCompactions + 1); }
        // Claude receives -p at native launch. Model output confirms acceptance;
        // process existence or a system/init event alone does not.
        if (e.type === 'assistant' || e.type === 'result' && (!e.is_error || e.num_turns > 0)) this.acknowledgePrompt();
        if (e.type === 'assistant') this.observeStatus((e.message?.content ?? []).filter(block => block.type === 'text').map(block => block.text).join('\n'));
        if (e.type === 'assistant') for (const block of e.message?.content ?? []) {
          if (block.type === 'text') { this.show(block.text); }
          if (block.type === 'tool_use') {
            this.count(block.id ?? `${e.message?.id ?? e.uuid ?? 'unknown'}:${block.name}`);
            if (block.id && this.toolNames.size < 4096) this.toolNames.set(block.id, safeName(block.name));
            if (block.id && typeof block.input?.command === 'string' && this.toolCommands.size < 4096) this.toolCommands.set(block.id, block.input.command.replace(/[\x00-\x1f\x7f]+/g, ' ').slice(0, 300));
            this.act(block.name);
          }
        }
        if (e.type === 'user') for (const block of e.message?.content ?? []) {
          if (block.type !== 'tool_result' || block.is_error !== true) continue;
          const content = typeof block.content === 'string' ? block.content : Array.isArray(block.content) ? block.content.map(v => typeof v.text === 'string' ? v.text : '').join(' ') : '';
          if (/permission.*denied|requires approval|approval.*required/i.test(content)) this.observeDenial(block.tool_use_id, this.toolNames.get(block.tool_use_id));
        }
        if (e.type === 'result') {
          this.identify(e.session_id);
          this.report = { is_error: e.is_error === true, subtype: safeName(e.subtype), num_turns: counter(e.num_turns),
            session_id: this.sessionId, usage: e.usage ? { input_tokens: e.usage.input_tokens, output_tokens: e.usage.output_tokens,
              cache_read_input_tokens: e.usage.cache_read_input_tokens, cache_creation_input_tokens: e.usage.cache_creation_input_tokens } : null,
            result: text(e.result, 32 * 1024), errors: Array.isArray(e.errors) ? e.errors.slice(0, 5).map(v => text(v)) : [],
            permission_denials: Array.isArray(e.permission_denials) ? e.permission_denials.slice(0, 100).map(v => ({ tool_name: safeName(v?.tool_name) })) : [] };
          for (const denial of Array.isArray(e.permission_denials) ? e.permission_denials.slice(0, 100) : []) this.observeDenial(denial.tool_use_id, denial.tool_name);
          this.observeClaudeWindow(e.modelUsage);
          this.show(e.result, 'Agent result');
        }
      }
    }
  }
}

// App Server protocol: initialize → start/resume → turn/start → ordered notifications.
// Only this thread's scalar metadata survives parsing; no conversation history is requested.
class CodexStream extends ProviderStream {
  constructor(options) { super('codex', options); this.rpc = options.rpc; this.threadId = null; this.turnId = null;
    this.tokenTotals = null; this.nativeContext = null; this.compactionIds = new Set(); this.closed = false; this.nextId = 10; this.interrupted = false;
    this.phase = 'initialize'; this.requestId = 1; }
  attach(process_) {
    this.process = process_;
    this.attachedAt = Date.now();
    // Named thread permissions are experimental in Codex 0.160; preflight pins that minimum version.
    this.send({ id: 1, method: 'initialize', params: { clientInfo: this.rpc.clientInfo, capabilities: { experimentalApi: true } } });
    this.setupTimer = setTimeout(() => { this.fail('Codex startup timed out before starting project work.', 'native_startup_timeout'); }, 45_000);
  }
  send(value) { if (!this.closed && !this.process.stdin.destroyed) this.process.stdin.write(JSON.stringify(value) + '\n'); }
  cleanup() { clearTimeout(this.setupTimer); clearTimeout(this.closeTimer); }
  finish() {
    if (this.closed) return; this.closed = true; this.cleanup(); this.process.stdin.end();
    this.closeTimer = setTimeout(() => this.process.kill('SIGKILL'), 5000);
  }
  fail(message, code = 'native_rpc_error', details = {}) {
    if (this.closed) return;
    this.failure = { code, phase: this.phase, request_id: this.requestId,
      elapsed_ms: Math.max(0, Date.now() - this.attachedAt), ...details };
    // Native error text is used for classification only, never copied to status.
    this.report = { is_error: true, usage: null, result: '', errors: [text(message)] }; this.finish();
  }
  overflow(bytes) { this.fail('Codex protocol response exceeded the bounded frame limit.', 'native_protocol_frame_too_large', { frame_bytes_at_least: bytes }); }
  interrupt() {
    this.interrupted = true;
    if (this.threadId && this.turnId) this.send({ id: this.nextId++, method: 'turn/interrupt', params: { threadId: this.threadId, turnId: this.turnId } });
    else this.process.kill('SIGINT');
  }
  line(line) {
    if (this.closed) return;
    let e; try { e = JSON.parse(line); } catch { return; }
    if (!e || typeof e !== 'object') return;
    const rpcError = () => this.fail(e.error.message, 'native_rpc_error', { rpc_code: Number.isSafeInteger(e.error.code) ? e.error.code : null });
    if (e.id === 1 && this.requestId === 1) {
      if (e.error) return rpcError();
      if (this.interrupted) return this.finish();
      this.send({ method: 'initialized', params: {} });
      this.phase = 'native_permissions'; this.requestId = 4;
      this.send({ id: 4, method: 'config/read', params: { cwd: this.rpc.startParams.cwd, includeLayers: Boolean(this.rpc.nativeRuleLayer) } });
      return;
    }
    if (e.id === 4 && this.requestId === 4) {
      if (e.error) return rpcError();
      if (this.rpc.nativeRuleLayer) {
        const key = value => process.platform === 'win32' ? value.toLowerCase() : value;
        const layer = Array.isArray(e.result?.layers) ? e.result.layers.find(value => value?.name?.type === 'project' && typeof value.name.dotCodexFolder === 'string' && key(value.name.dotCodexFolder) === key(this.rpc.nativeRuleLayer)) : null;
        if (!layer || layer.disabledReason != null) return this.fail('The worker native merge-rule layer is not trusted by Codex. Trust the project through Codex before starting this worker.', 'merge_policy_unavailable');
      }
      let params;
      try { params = this.rpc.prepareThread(e.result?.config); }
      catch { return this.fail('Cannot preserve Codex permissions while protecting Minions private state.', 'native_permissions_unavailable'); }
      if (this.interrupted) return this.finish();
      this.phase = this.rpc.resuming ? 'thread_resume' : 'thread_start'; this.requestId = 2;
      this.send({ id: 2, method: this.rpc.resuming ? 'thread/resume' : 'thread/start', params });
      return;
    }
    if (e.id === 2 && this.requestId === 2) {
      if (e.error) return rpcError();
      const r = e.result;
      if (!this.rpc.permissionProfile || r?.activePermissionProfile?.id !== this.rpc.permissionProfile
        || r.approvalPolicy !== 'on-request' || r.approvalsReviewer !== 'auto_review') return this.fail('Codex did not confirm the required worker permissions.', 'native_permissions_unavailable');
      if (!UUID.test(r?.thread?.id ?? '') || r.modelProvider !== 'openai') return this.fail('Codex returned an unsupported thread/provider identity.', 'native_protocol_error');
      if (this.rpc.resuming && r.thread.id !== this.rpc.startParams.threadId) return this.fail('Codex resumed a different thread than the approved session.', 'native_protocol_error');
      if(this.rpc.effort&&r.reasoningEffort!==this.rpc.effort)return this.fail('Codex did not confirm the pinned reasoning effort.', 'native_protocol_error');
      this.threadId = r.thread.id; this.identify(this.threadId);
      if (this.interrupted) return this.finish();
      this.observeModel({ model: safeName(r.model), modelSource: 'client-selected', ...(this.rpc.effort?{effort:this.rpc.effort}:{}) });
      this.phase = 'turn_start'; this.requestId = 3;
      const send = () => {
        // A cancellation or persistence failure during the awaited commit cannot
        // submit a late turn. Initialization alone is never model acceptance.
        if (this.closed) return;
        if (this.interrupted) return this.finish();
        if (this.delivery === 'submitted') this.send({ id: 3, method: 'turn/start', params: { threadId: this.threadId, input: [{ type: 'text', text: this.rpc.prompt }], ...(this.rpc.effort?{effort:this.rpc.effort}:{}) } });
      };
      const committed = this.submitPrompt();
      if (committed) committed.then(send).catch(error => { try { this.persistence(error); } catch {} }); else send();
      return;
    }
    if (e.id === 3 && this.requestId === 3) {
      if (e.error) { if (this.delivery !== 'acknowledged') this.delivery = 'rejected'; return rpcError(); }
      if (this.turnId && e.result?.turn?.id !== this.turnId) return this.fail('Codex returned a conflicting turn identity.', 'native_protocol_error');
      this.turnId ??= e.result?.turn?.id;
      if (!safeName(this.turnId)) return this.fail('Codex returned no valid turn identity.', 'native_protocol_error');
      this.acknowledgePrompt(); this.phase = 'turn'; this.requestId = null; clearTimeout(this.setupTimer);
      if (this.interrupted) this.interrupt(); return;
    }
    if (e.method && e.id !== undefined) {
      if (e.method === 'item/commandExecution/requestApproval' || e.method === 'item/fileChange/requestApproval') {
        // Native automatic review handles permitted local work. If an approval
        // still reaches this headless client, nobody can answer it here. Decline
        // only this action so the agent can report the blocker and keep working.
        this.observeDenial(String(e.id), e.method === 'item/fileChange/requestApproval' ? 'fileChange' : 'Bash');
        this.send({ id: e.id, result: { decision: 'decline' } });
        return; // Decline preserves this turn so unrelated work can continue.
      }
      // Unknown interactive requests never acquire authority from local approval.

      this.send({ id: e.id, error: { code: -32601, message: 'This foreground adapter cannot answer interactive requests.' } });
      return this.fail(`Codex requested interactive input (${safeName(e.method) ?? 'unknown'}); review the local execution policy.`, 'native_interactive_request');
    }
    const v = e.params;
    if (!v || v.threadId !== this.threadId) return;
    if (e.method === 'turn/started') {
      if (!safeName(v.turn?.id)) return this.fail('Codex returned no valid turn identity.', 'native_protocol_error');
      if (this.turnId && v.turn.id !== this.turnId) return;
      this.turnId = v.turn.id; this.acknowledgePrompt(); this.phase = 'turn'; clearTimeout(this.setupTimer);
    }
    if (v.turnId && this.turnId && v.turnId !== this.turnId) return;
    if (e.method === 'model/rerouted') this.observeModel({ model: safeName(v.toModel), modelSource: 'provider-rerouted' });
    if (e.method === 'thread/tokenUsage/updated' && this.turnId) {
      const t = v.tokenUsage?.total;
      if (t) this.tokenTotals = [t.inputTokens, t.outputTokens, t.cachedInputTokens, t.cacheWriteInputTokens].map(counter);
      if(v.turnId===this.turnId&&v.tokenUsage?.last){
        const lastInputTokens=counter(v.tokenUsage.last.inputTokens),lastTotalTokens=counter(v.tokenUsage.last.totalTokens),modelContextWindow=counter(v.tokenUsage.modelContextWindow);
        if(lastInputTokens!==null||lastTotalTokens!==null){
          this.nativeContext={source:'codex-app-server',coverage:'partial-turn-stream',lastInputTokens,lastTotalTokens,modelContextWindow,
            observations:Math.min(1e9,(this.nativeContext?.observations??0)+1),completedCompactions:this.nativeContext?.completedCompactions??0};
        }
      }
    }
    if (e.method === 'item/started' || e.method === 'item/completed') {
      const item = v.item;
      if(e.method==='item/completed'&&v.turnId===this.turnId&&item?.type==='contextCompaction'&&safeName(item.id)&&!this.compactionIds.has(item.id)&&this.compactionIds.size<4096){
        this.compactionIds.add(item.id);
        this.nativeContext??={source:'codex-app-server',coverage:'partial-turn-stream',lastInputTokens:null,lastTotalTokens:null,modelContextWindow:null,observations:0,completedCompactions:0};
        this.nativeContext.completedCompactions++;
      }
      if (['commandExecution', 'mcpToolCall', 'fileChange', 'webSearch', 'dynamicToolCall', 'imageGeneration'].includes(item?.type)) {
        this.count(item.id); if (e.method === 'item/started') this.act(item.type);
      }
      if (e.method === 'item/completed' && item?.type === 'agentMessage') { this.finalText = text(item.text, 32 * 1024); if (this.turnId && v.turnId === this.turnId) this.observeStatus(this.finalText); this.show(item.text); }
    }
    if (e.method === 'turn/completed') {
      if (this.turnId && v.turn?.id !== this.turnId) return;
      const baseline = this.rpc.baseline;
      const values = this.tokenTotals?.map((n, i) => n !== null && baseline?.[i] !== null && counter(baseline?.[i]) !== null && n >= baseline[i] ? n - baseline[i] : undefined);
      this.report = { is_error: v.turn?.status !== 'completed', result: this.finalText,
        usage: values ? { input_tokens: values[0], output_tokens: values[1], cached_input_tokens: values[2], cache_write_input_tokens: values[3] } : null,
        errors: v.turn?.error?.message ? [text(v.turn.error.message)] : [] };
      if (this.report.is_error) this.failure = { code: 'native_turn_failed', phase: 'turn', request_id: null, elapsed_ms: Math.max(0, Date.now() - this.attachedAt) };
      this.finish();
    }
  }
}
