// Only standalone assistant-text markers outside code fences. Never evaluates shell text.
export function agentStatuses(value) {
  if (typeof value !== 'string') return [];
  const statuses = []; let fence = null;
  for (const line of value.split(/\r?\n/)) {
    const edge = /^\s*(`{3,}|~{3,})(.*)$/.exec(line);
    if (edge) {
      if (!fence) fence = edge[1];
      else if (edge[1][0] === fence[0] && edge[1].length >= fence.length && !edge[2].trim()) fence = null;
      continue;
    }
    if (fence || !line.startsWith('AGENT_STATUS=') || line.length > 2200) continue;
    try {
      const status = JSON.parse(line.slice('AGENT_STATUS='.length));
      if (typeof status === 'string' && status.trim() && [...status].length <= 180 && !/[\u0000-\u001f\u007f-\u009f\u2028\u2029]/u.test(status)) statuses.push(status.trim());
    } catch { /* Malformed/missing status never fails useful work. */ }
  }
  return statuses;
}
