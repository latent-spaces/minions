// The app's one icon set: Phosphor, rounder and softer than the earlier set (owner, 16 November 2026).
// Components keep their familiar names and props (size, strokeWidth, className, aria-*), so call sites stay as they were;
// a heavier strokeWidth (2 or more) maps to Phosphor's bold weight.
import type { ComponentType, SVGProps } from 'react';
import * as P from '@phosphor-icons/react';
import type { Icon as PhosphorIcon } from '@phosphor-icons/react';

export type LucideProps = Omit<SVGProps<SVGSVGElement>, 'ref'> & { size?: number | string; strokeWidth?: number | string; absoluteStrokeWidth?: boolean };
export type LucideIcon = ComponentType<LucideProps>;

function icon(Glyph: PhosphorIcon, flip = false): LucideIcon {
  const Wrapped = ({ size = 24, strokeWidth, absoluteStrokeWidth: _absolute, style, ...rest }: LucideProps) =>
    <Glyph size={size} weight={Number(strokeWidth) >= 2 ? 'bold' : 'regular'} style={flip ? { transform: 'scaleX(-1)', ...style } : style} {...(rest as object)} />;
  Wrapped.displayName = Glyph.displayName;
  return Wrapped;
}

