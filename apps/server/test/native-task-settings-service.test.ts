import { randomUUID } from 'node:crypto';
import { beforeEach, expect, test } from 'vitest';
import { nativeTasksEnabled } from '@mlswarm/contracts';
import { db, inProject, profiles } from '../src/firestore.js';
import { saveNativeTaskSettings, readNativeTaskSettings } from '../src/projects/native-task-settings.js';
import { mutateNativeTask, getNativeTask } from '../src/projects/native-tasks.js';
import { readWorkspace } from '../src/projects/store.js';
import { recordWorkIntent } from '../src/v2/work-intents.js';
import { startRun } from '../src/v2/runs.js';
import { resetEmulator, seed, TEST_PROJECT } from './helpers.js';

beforeEach(resetEmulator);
test('optional task capability defaults ON, rejects unauthorized/stale setting edits, preserves records OFF and has stable retries', async () => inProject(TEST_PROJECT, async () => {
  const f = await seed({ profiles: [{ name: 'Admin', email: 'admin@example.test', role: 'owner' }, { name: 'Member', email: 'member@example.test' }], agents: [{ person: 1, name: 'Otter' }] });
  const person = { id: f.personIds[0], ...(await profiles.doc(f.personIds[0]).get()).data()! }, actor = { kind: 'person' as const, person };
  expect(nativeTasksEnabled()).toBe(true);
  expect(await readNativeTaskSettings(person.id)).toEqual({ enabled: true, revision: 0 });
  expect((await readWorkspace(person, TEST_PROJECT)).nativeTasks).toEqual({ enabled: true, revision: 0 });
  const create = { operation: 'create', title: 'Retained native work', clientRequestId: randomUUID() };
  const { task } = await mutateNativeTask(actor, create, () => 1000);
  const off = { enabled: false, expectedRevision: 0, clientRequestId: randomUUID() };
  await expect(saveNativeTaskSettings(f.personIds[1], off)).rejects.toMatchObject({ code: 'forbidden' });
  const beforeAgents = (await db.collection(`projects/${TEST_PROJECT}/agents`).get()).docs.map(row => row.data());
  expect(await saveNativeTaskSettings(person.id, off)).toEqual({ enabled: false, revision: 1 });
  expect(await saveNativeTaskSettings(person.id, off)).toEqual({ enabled: false, revision: 1 });
  await expect(saveNativeTaskSettings(person.id, { ...off, clientRequestId: randomUUID() })).rejects.toMatchObject({ code: 'intent_conflict' });
  await expect(saveNativeTaskSettings(person.id, { ...off, enabled: true })).rejects.toMatchObject({ code: 'intent_conflict' });
  await expect(mutateNativeTask(actor, create, () => 1000)).rejects.toMatchObject({ code: 'tasks_disabled' });
  await expect(mutateNativeTask(actor, { operation: 'comment', taskId: task.id, expectedRevision: 1, clientRequestId: randomUUID(), body: 'Stale tool call' }, () => 1000)).rejects.toMatchObject({ code: 'tasks_disabled' });
  expect((await getNativeTask(actor, task.id)).activity).toHaveLength(1);
  expect((await readWorkspace(person, TEST_PROJECT)).nativeTasks).toEqual({ enabled: false, revision: 1 });
  expect((await db.collection(`projects/${TEST_PROJECT}/agents`).get()).docs.map(row => row.data())).toEqual(beforeAgents);
  const run = await startRun(f.agents[0].agentId, { clientRunId: randomUUID(), runnerVersion: 'test', takeover: false }, () => 1000);
  const input = { intent_id: 'ordinary-work', client_request_id: 'ordinary', expected_revision: 0, state: 'runnable', next_step: 'Continue approved source work' };
  expect((await recordWorkIntent(f.agents[0].agentId, run.run_id, input, () => 1000)).intent.taskId).toBeNull();
  await expect(recordWorkIntent(f.agents[0].agentId, run.run_id, { ...input, intent_id: 'task-work', client_request_id: 'linked', task_id: task.id }, () => 1000)).rejects.toMatchObject({ code: 'tasks_disabled' });
  expect(await saveNativeTaskSettings(person.id, { enabled: true, expectedRevision: 1, clientRequestId: randomUUID() })).toEqual({ enabled: true, revision: 2 });
  expect(await mutateNativeTask(actor, create, () => 1000)).toMatchObject({ task });
  expect((await getNativeTask(actor, task.id)).activity).toHaveLength(1);
}));
